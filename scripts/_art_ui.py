def school_icon(r, idx):
    """6 个流派徽记。"""
    w = '#f4f8fc'
    w2 = '#a8b8c8'
    if idx == 0:      # 余烬：火
        r.poly([(48, 12), (66, 40), (60, 50), (72, 60), (60, 80), (48, 86),
                (36, 78), (26, 58), (38, 44), (42, 28)], w)
        r.poly([(48, 36), (56, 52), (50, 68), (44, 56)], w2)
    elif idx == 1:    # 疾风：三旋
        for i in range(3):
            r.arc((20 + i * 3, 16 + i * 16, 78 - i * 3, 62 + i * 16), 200, 20, w, 6.0 - i)
            r.line([(48 + i * 4, 30 + i * 12), (70 + i * 3, 32 + i * 12)], w, 5.0)
    elif idx == 2:    # 霜星：六角星
        for i in range(6):
            a = i * math.pi / 3 - math.pi / 2
            r.poly([(48 + math.cos(a) * 30, 48 + math.sin(a) * 30),
                    (48 + math.cos(a + .52) * 10, 48 + math.sin(a + .52) * 10),
                    (48 + math.cos(a - .52) * 10, 48 + math.sin(a - .52) * 10)], w)
        r.ell((42, 42, 54, 54), w2)
    elif idx == 3:    # 生命：叶
        r.poly([(48, 16), (70, 42), (48, 80), (26, 42)], w)
        r.line([(48, 22), (48, 76)], w2, 3.0)
        for i in range(4):
            r.line([(48, 32 + i * 12), (60, 36 + i * 12)], w2, 2.4)
            r.line([(48, 32 + i * 12), (36, 36 + i * 12)], w2, 2.4)
    elif idx == 4:    # 雷光：闪电
        r.poly([(54, 10), (30, 50), (44, 50), (36, 86), (66, 42), (50, 42)], w)
        r.poly([(52, 22), (40, 46), (48, 46), (44, 76), (58, 46), (50, 46)], w2)
    else:             # 虚空：裂眼
        r.ell((16, 30, 80, 66), w)
        r.ell((36, 38, 60, 58), w2)
        r.ell((42, 42, 54, 54), '#6a7a8a')
        for i in range(3):
            r.line([(18 + i * 8, 24 + i * 4), (30 + i * 8, 34 + i * 4)], w, 3.0)
            r.line([(78 - i * 8, 24 + i * 4), (66 - i * 8, 34 + i * 4)], w, 3.0)


