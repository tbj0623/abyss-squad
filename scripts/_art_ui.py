def draw_ui_atlas():
    """返回 1536x384 RGBA 图集。"""
    from PIL import Image
    atlas = Image.new('RGBA', (UC * 16, UC * 4), (0, 0, 0, 0))
    for i in range(16):
        r = Rig(5000 + i, UC, UC)
        relic_icon(r, i)
        atlas.paste(r.final(rim=('#ffffff', .28), shadow=None, grain=0, key=.35,
                            outline=1, glow_blur=7.0), (i * UC, 0))
    for i in range(6):
        r = Rig(5100 + i, UC, UC)
        school_icon(r, i)
        atlas.paste(r.final(rim=('#ffffff', .30), shadow=None, grain=0, key=.35,
                            outline=1, glow_blur=7.0), (i * UC, UC))
    for i in range(12):
        r = Rig(5200 + i, UC, UC)
        role_badge(r, i)
        atlas.paste(r.final(rim=('#ffffff', .24), shadow=None, grain=0, key=.35,
                            outline=1, glow_blur=6.0), ((i % 16) * UC, UC * 2))
    return atlas
